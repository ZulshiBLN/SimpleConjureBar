-- The names Bindings.xml's keys show in the game's Key Bindings. Set for every class - this file
-- loads before the mage check - so a key bound on the mage keeps its name on other characters,
-- where it does nothing; for a mage they follow the addon language.
local BINDINGS = {
    ["CLICK SimpleConjureBarBuffAll:LeftButton"] = "KEY_BUFF_ALL",
    ["CLICK SimpleConjureBarSettingsKey:LeftButton"] = "OPEN_SETTINGS",
    ["CLICK SimpleConjureBar_Intellect:MiddleButton"] = "BUFF_RUN",
}
local function NameBindings()
    BINDING_HEADER_SIMPLECONJUREBAR = "SimpleConjureBar"
    for binding, key in pairs(BINDINGS) do
        _G["BINDING_NAME_" .. binding] = active[key] or locales.enUS[key]
    end
end
NameBindings()

function ns.SetLocale(code)
    if not locales[code] then code = client end
    active, activeCode = locales[code], code
    NameBindings()
end
function ns.GetLocaleCode() return activeCode end
ns.L = setmetatable({}, {
    __index = function(_, key)
        return active[key] or locales.enUS[key] or key
    end,
})
